// سلّم الرتب الموسمية (مشجّع → لاعب → فارس → أمير → الملك).
//
// محسوب في العميل عمداً: السلّم قرار عرض لا حقيقة في قاعدة البيانات،
// فلو تغيّرت عتباته غداً نغيّر ملفاً واحداً بلا ترحيل بيانات ولا مسار
// جديد في السيرفر. كان داخل شاشة العرش؛ نُقل هنا حين احتاجته منصّة
// التتويج المشتركة وملف اللاعب.
/// سلّم الرتب الموسمية كما في ملف الهوية.
enum Rank {
  fan('مشجّع', 0),
  player('لاعب', 500),
  knight('فارس', 1500),
  prince('أمير', 3000),
  king('الملك', 5000);

  final String label;
  final int from;
  const Rank(this.label, this.from);

  static Rank of(int points) {
    // من الأعلى للأدنى: أول عتبة يبلغها المستخدم هي رتبته.
    for (final r in Rank.values.reversed) {
      if (points >= r.from) return r;
    }
    return Rank.fan;
  }
}

