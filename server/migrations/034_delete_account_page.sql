## ما الذي يُحذف

يُحذف حسابك وكل ما ارتبط به حذفاً نهائياً من قاعدة بياناتنا:

- بريدك الإلكتروني واسمك المعروض وصورة ملفك.
- توقعاتك كلها ونقاطك ورتبتك وسلاسلك وأوسمتك.
- عضوياتك في المجالس، وسجلّ اشتراكك ومشترياتك عندنا.
- أجهزتك المسجّلة للإشعارات، وجلساتك المفتوحة على كل جهاز.

ويختفي اسمك من لوحات الترتيب ومن مجالس أصدقائك.

**المجالس التي تملكها**: تنتقل ملكيتها إلى عضو آخر إن وُجد، وتُحذف مع
حسابك إن كنت عضوها الوحيد.

