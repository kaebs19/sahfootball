-- ٠٤٢ — نقاط الإضافة: ٣/٢/١ لأفضل ثلاثة في كل مباراة.
--
-- الثقب الذي تسدّه: جدول النقاط يكافئ الحدث الظاهر (هدف، صناعة،
-- شباك نظيفة) ولا يرى الأداء نفسه. فمدافعٌ صمد تسعين دقيقة أمام
-- هجومٍ كامل ومرّر الكرة الأخيرة قبل صانعها يخرج بنقطتين، بينما
-- مهاجمٌ لمس الكرة ثلاث مرات وسجّل واحدة يخرج بستّ. ونقاط
-- الإضافة هي ما يجعل «من لعب جيداً» سؤالاً له جواب.
--
-- عمودان لا واحد:
--
-- `bps` هو المؤشّر الخام (عشرات النقاط) الذي تُرتَّب به المباراة،
-- و`bonus` هو ما نالَه فعلاً (٣ أو ٢ أو ١ أو صفر). ولماذا نخزّن
-- المؤشّر وقد استُهلك؟ لأن أول سؤال يصل حين لا ينال اللاعب
-- الإضافة هو «لماذا هو لا أنا؟» — وبلا المؤشّر لا جواب إلا إعادة
-- الحساب، وإعادةُ الحساب بعد أشهر بجدولٍ عُدّل تعطي رقماً آخر.
--
-- والعمودان في صفّ الإحصاء لا في صفّ التشكيلة: الإضافة تخصّ
-- اللاعب في المباراة لا التشكيلة التي ضمّته، ومن ضمّه عشرة
-- مدرّبين يجب أن يروا الرقم نفسه محسوباً مرة واحدة.
ALTER TABLE player_fixture_stats
  ADD COLUMN IF NOT EXISTS bps   INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS bonus INTEGER NOT NULL DEFAULT 0;

-- ترتيب المباراة الواحدة تنازلياً بالمؤشّر — وهو كل ما تفعله
-- دالة التوزيع، ويُقرأ كذلك في بطاقة «لماذا هو لا أنا؟».
CREATE INDEX IF NOT EXISTS idx_player_stats_bps
  ON player_fixture_stats (fixture_id, bps DESC);
