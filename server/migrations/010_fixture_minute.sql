-- 010_fixture_minute.sql — دقيقة اللعب الجارية
--
-- تبويب "مباشر" يعرض النتيجة الحية، لكن النتيجة وحدها ناقصة:
-- "2-1" لا تخبر المشاهد إن كان أمامه شوط كامل ليتغير كل شيء أم
-- ثلاث دقائق. الدقيقة هي ما يحوّل الرقم إلى حالة.
--
-- ولماذا نخزّنها بدل حسابها من kickoff_at؟
-- الحساب من الساعة (now() - kickoff_at) يبدو كافياً ويخطئ دائماً:
--   • الوقت بدل الضائع: المباراة تستمر بعد 45 و 90 بدقائق لا يعرفها
--     أحد مسبقاً، فالساعة تسبق الدقيقة الحقيقية.
--   • استراحة بين الشوطين ~15 دقيقة يتوقف فيها العداد تماماً،
--     وساعة الحائط لا تتوقف — بعد الاستراحة يصبح فارق ربع ساعة ثابتاً.
--   • التوقف لإصابة أو VAR أو مطر، وتأخر صافرة البداية عن الموعد
--     المعلن، وأشواط إضافية تعيد العد بمنطق آخر.
-- المزوّد يرسل الدقيقة الرسمية الحقيقية (status.elapsed) في كل نبضة،
-- فالصواب أن نحفظ ما يقوله الحكَم لا ما تقوله ساعتنا.
--
-- nullable عمداً: قبل صافرة البداية لا توجد دقيقة، وبعد صافرة
-- النهاية لا معنى لها. NULL هنا يعني "لا ينطبق" وليس "مجهول"،
-- ولهذا لا نضع DEFAULT 0 — الصفر رقم يوحي بأن المباراة في دقيقتها
-- الأولى، وهو أسوأ من غياب القيمة.
ALTER TABLE fixtures ADD COLUMN IF NOT EXISTS elapsed INTEGER;
