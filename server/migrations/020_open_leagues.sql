-- 020 — خمسة دوريات تدخل اللعبة، وعمود يتذكّر من هُيِّئ.
--
-- كانت 271 مباراة قابلة للتوقّع مقابل 1,932 تُعرض ولا تُلعب. وأي
-- شاشة تسأل "أي دوري تتابع؟" على هذا الحال تَعِد بما لا تملك: من
-- يختار الإنجليزي يصطدم بأن لا شيء فيه يُتوقَّع — وعدٌ يُكسر في
-- أول شاشة يراها.
--
-- الأبطال (أوروبا وآسيا) تبقى خارج اللعبة عمداً: مبارياتها
-- متقطّعة ومجموعاتها تتبدّل، فـ"فريقك" فيها لا يعطي تدفّقاً
-- مستمرّاً من المباريات — وهو أساس التهيئة كلها.
UPDATE leagues SET in_app = true
 WHERE id IN (39, 140, 135, 78, 61)   -- الإنجليزي، الإسباني، الإيطالي، الألماني، الفرنسي
   AND enabled;

-- من أنهى التهيئة (أو تخطّاها) لا يُسأل ثانية.
--
-- عمود على المستخدم لا صف في جدول حالات: السؤال ثنائي ولا تاريخ
-- له، والوقت نفسه هو الجواب. ونستعمل NULL لا false لأن "متى"
-- يفيدنا لاحقاً في قياس أثر التهيئة، و false لا يفيد بشيء.
ALTER TABLE users ADD COLUMN onboarded_at TIMESTAMPTZ;
