-- 012_notifications.sql — الإشعارات: أجهزة المستخدم، تفضيلاته، وما أُرسل فعلاً
--
-- ثلاث قطع، كل واحدة تحل مشكلة مختلفة تماماً:
--   device_tokens      — إلى أين نرسل
--   users.notify_*     — هل يريد المستخدم أن نرسل
--   sent_notifications — هل أرسلنا هذا من قبل

-- ── 1) أجهزة المستخدم ────────────────────────────────────────────
--
-- التوكن هو المفتاح الأساسي وليس (user_id, token)، والفرق ليس
-- شكلياً: الجهاز الواحد يصدر توكناً واحداً مهما تبدّل من يسجّل
-- الدخول عليه. لو كان المفتاح مركّباً لبقي صف علي بعد أن يخرج
-- ويدخل عمر على نفس الهاتف، فيصل إشعار "لم تتوقّع بعد" الخاص بعلي
-- إلى شاشة عمر — تسريب بيانات صغير لكنه حقيقي. بجعل التوكن مفتاحاً،
-- التسجيل الجديد يمر بـ ON CONFLICT DO UPDATE وينقل الجهاز لصاحبه
-- الحالي بصف واحد.
--
-- platform مقيّد بقيمتين: APNs و FCM بروتوكولان مختلفان تماماً،
-- والمرسل يختار حسب هذا العمود. قيمة ثالثة مكتوبة بخطأ إملائي
-- تعني جهازاً لا يصله شيء أبداً ولا خطأ يظهر في اللوق.
CREATE TABLE IF NOT EXISTS device_tokens (
  token        TEXT PRIMARY KEY,
  user_id      UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  platform     TEXT NOT NULL CHECK (platform IN ('ios', 'android')),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- يُحدَّث مع كل تسجيل من التطبيق. توكن لم يُر منذ شهور غالباً
  -- لتطبيق محذوف؛ العمود يسمح بتنظيفه لاحقاً دون تخمين.
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- السؤال الوحيد الذي نسأله: "أجهزة هؤلاء المستخدمين". المفتاح
-- الأساسي مرتب بالتوكن فلا يخدم هذا الاتجاه.
CREATE INDEX IF NOT EXISTS idx_device_tokens_user ON device_tokens (user_id);

-- ── 2) تفضيلات المستخدم ──────────────────────────────────────────
--
-- عمودان على users بنفس منطق 008_user_status: الحالة ثنائية،
-- والفحص يجري داخل استعلام الإرسال نفسه — جدول تفضيلات مستقل
-- يفرض JOIN إضافياً مقابل صفر مكسب.
--
-- الافتراضي true لأن المستخدم أعطى إذن الإشعارات لتوّه في نظام
-- التشغيل؛ أن نصمت بعدها حتى يجدها في الإعدادات ويشعّلها = لن
-- يصله شيء أبداً. إذن النظام هو البوابة الحقيقية، وهذه الأعمدة
-- تحكّم دقيق داخل التطبيق لا بديل عنها.
ALTER TABLE users ADD COLUMN IF NOT EXISTS notify_reminders BOOLEAN NOT NULL DEFAULT true;
ALTER TABLE users ADD COLUMN IF NOT EXISTS notify_results   BOOLEAN NOT NULL DEFAULT true;

-- ── 3) سجل ما أُرسل ──────────────────────────────────────────────
--
-- هذا الجدول هو كل قصة "لا نزعج أحداً مرتين". وظيفة التذكير تعمل
-- كل بضع دقائق وتسأل نفس السؤال في كل مرة: "من لم يتوقّع لمباراة
-- تنطلق قريباً؟" — والجواب يبقى نعم حتى ينطلق اللقاء. بلا هذا
-- الجدول يصل الإشعار نفسه كل خمس دقائق لساعتين، وهو أسرع طريق
-- لأن يوقف المستخدم الإشعارات نهائياً (وذلك قرار لا رجعة فيه
-- عملياً: إذن iOS يُطلب مرة واحدة).
--
-- المفتاح المركّب هو الضمانة، لا فحص "هل أرسلنا؟" في الكود:
-- الفحص ثم الإرسال فيهما فجوة، ونسختان من الوظيفة (سيرفران خلف
-- موازن أحمال) تمران بالفجوة معاً. القاعدة لا تسمح بذلك.
--
-- ref هو معرّف المباراة في النوعين الحاليين، ولذلك هو نص لا رقم:
-- إشعار مستقبلي عن مجموعة أو عن سلسلة سيحمل مرجعاً من نوع آخر،
-- ولا نريد هجرة قاعدة بيانات لإضافة نوع إشعار — نفس قرار
-- badge_key في 011.
CREATE TABLE IF NOT EXISTS sent_notifications (
  user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind    TEXT NOT NULL,
  ref     TEXT NOT NULL,
  sent_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, kind, ref)
);

-- للتنظيف الدوري: الصفوف الأقدم من موسم لا قيمة لها، وحذفها
-- بمسح كامل للجدول يصير مكلفاً مع نمو المستخدمين.
CREATE INDEX IF NOT EXISTS idx_sent_notifications_at ON sent_notifications (sent_at);
