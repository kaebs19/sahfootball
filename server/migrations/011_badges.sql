-- 011_badges.sql — الأوسمة: ما ناله كل مستخدم من إنجازات
--
-- جدول واحد فقط، يسجّل ما نيل فعلاً. ولا جدول تعريفات للأوسمة،
-- والسبب أن الوسام ليس صفاً بل قاعدة: "خمسة توقعات صحيحة متتالية"
-- شرط لا يُحسم إلا باستعلام. جدول badges سيحمل الاسم ونص الشرط
-- بينما القاعدة التي تُطبَّق تبقى في JS حتماً، فتصير للحقيقة نسختان:
-- يعدّل أحدهم عتبة السلسلة في الكود وينسى الصف، فيقرأ المستخدم
-- شرطاً لا يطابق ما يُقاس عليه — وهو أسوأ من خطأ ظاهر لأنه يبدو
-- سليماً. الكتالوج كله (المفتاح، الاسم، الشرط، الفحص) في
-- src/services/badgeService.js في مكان واحد لا ينحرف عن نفسه.
--
-- المفتاح الأساسي المركّب (user_id, badge_key) هو كل قصة أمان
-- التكرار: المقيّم يعمل عند كل احتساب نقاط وعند كل فتح لشاشة
-- "ملفي"، فيحاول منح ما نيل سابقاً عشرات المرات. المفتاح يحوّل
-- المحاولة الثانية إلى تصادم، وكل إدراج في هذا الجدول يمر بـ
-- ON CONFLICT DO NOTHING فيسقط بصمت: لا صف مكرر، والأهم أن
-- earned_at يبقى لحظة النيل الأولى ولا يتقدم. (ولهذا لا يجوز
-- استعمال ON CONFLICT DO UPDATE هنا أبداً — يمحو تاريخ الإنجاز.)
--
-- badge_key نص حر بلا قيد على قيمه عمداً: إضافة وسام جديد يجب أن
-- تكون سطراً في الكتالوج لا هجرة قاعدة بيانات. ثمن ذلك أن مفتاحاً
-- حُذف من الكتالوج تبقى صفوفه — ولا ضرر: العرض يمر على الكتالوج
-- ويستعلم عن التواريخ، فالمفتاح المجهول لا يظهر لأحد.
--
-- ولا فهرس إضافي: المفتاح الأساسي مرتب بـ user_id أولاً، والسؤال
-- الوحيد الذي نسأله ("أوسمة هذا المستخدم") يقرأه مباشرة.
CREATE TABLE IF NOT EXISTS user_badges (
  user_id   UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  badge_key TEXT NOT NULL,
  earned_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, badge_key)
);
