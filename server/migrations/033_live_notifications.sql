-- 033 — الإشعارات الحيّة: أهداف لحظة وقوعها، والنتيجة على شاشة القفل.
--
-- كان عندنا نوعان: تذكير قبل الإقفال، ونتيجة بعد الاحتساب. وبينهما
-- تسعون دقيقة صامتة هي قلب التجربة كلها — الهدف الذي يقلب توقّعك
-- من «مضبوط» إلى «خارج المسار» يقع فيها، ولا يعرف المستخدم به إلا
-- حين يفتح التطبيق. هذه الهجرة تملأ الصمت.

-- ── 1) تفضيل ثالث: الأهداف المباشرة ─────────────────────────────
--
-- مفتاح مستقل لا يُدمج مع التذكير ولا مع النتيجة: هذا أكثر الأنواع
-- إلحاحاً (ثلاثة إشعارات في مباراة واحدة) ومن يريد النتيجة النهائية
-- دون أن يُقاطَع مع كل هدف يجب أن يجد المفتاح، وإلا أطفأ الكل من
-- إعدادات الهاتف — وذلك لا رجعة فيه عملياً في iOS.
ALTER TABLE users ADD COLUMN IF NOT EXISTS notify_live BOOLEAN NOT NULL DEFAULT true;

-- ── 2) توكنات النشاط الحيّ (Live Activity) ──────────────────────
--
-- في iOS تظهر النتيجة الجارية على شاشة القفل وفي الجزيرة الديناميكية
-- عبر «نشاط حيّ»، وهو يُحدَّث بدفعة APNs من نوع مختلف عن الإشعار
-- العادي وبتوكن مختلف: لكل نشاط توكنه الخاص، يصدره النظام حين يبدأ
-- النشاط ويصلح لتحديثه وحده. ولذلك جدول مستقل عن device_tokens —
-- ذاك «إلى أين نرسل الإشعارات» وهذا «أي نشاط نحدّث».
--
-- صنفان في الجدول نفسه يفرّقهما fixture_id:
--   • fixture_id محدّد  — توكن نشاط قائم لمباراة بعينها (update/end).
--   • fixture_id فارغ   — توكن «بدء بالدفع» (push-to-start، iOS 17.2+):
--     يسمح للسيرفر بأن يُنشئ النشاط عند صافرة البداية دون أن يكون
--     التطبيق مفتوحاً، وهو ما يجعل الميزة تعمل لمن توقّع صباحاً
--     ونسي المباراة مساءً.
--
-- التوكن هو المفتاح لنفس سبب device_tokens: الجهاز يصدره لا الحساب،
-- وتبديل الحساب على نفس الهاتف ينقله لصاحبه الحالي بصف واحد.
CREATE TABLE IF NOT EXISTS live_activity_tokens (
  token      TEXT PRIMARY KEY,
  user_id    UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  fixture_id INTEGER REFERENCES fixtures(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- السؤالان اللذان نسألهما: «أنشطة هذه المباراة» عند كل هدف،
-- و«توكنات هذا المستخدم» عند خروجه.
CREATE INDEX IF NOT EXISTS idx_live_activity_fixture ON live_activity_tokens (fixture_id);
CREATE INDEX IF NOT EXISTS idx_live_activity_user    ON live_activity_tokens (user_id);
