-- 029 — وحدات الإعلانات في الإعدادات.
--
-- الهجرة 027 زرعت `ads: {enabled}` وحدها، ثم صار للإعلانات وحدات
-- لكل منصّة. ولماذا في الإعدادات لا في التطبيق؟ لأن تبديل وحدة أو
-- إطفاء واحدة تعطّلت يصير قراراً لحظياً بدل نشرٍ ومراجعة متجر
-- تستغرق أياماً — والإعلانات بالذات تحتاج هذا: وحدة تتوقف عن
-- الامتلاء تُطفأ اليوم لا الأسبوع القادم.
--
-- الاستثناء الوحيد هو **معرّف التطبيق** (GADApplicationIdentifier)
-- الذي يبقى في Info.plist و AndroidManifest: حزمة الإعلانات تقرؤه
-- عند الإقلاع قبل أن يصل أي ردّ من خادمنا.
--
-- والقيم هنا وحدات جوجل التجريبية المعلنة للجميع: تعرض إعلاناً
-- حقيقي الشكل بلا حساب ولا أرباح. `test: true` هو ما يجعل ذلك
-- مقروءاً بدل أن يُكتشف بعد شهر من الأرباح الصفرية — واستبدالها
-- بالوحدات الحقيقية تعديلُ صفٍّ واحد هنا.
--
-- jsonb_set لا استبدال الكائن كله: قد يكون الأدمن عدّل السعر أو
-- عدد التعديلات المجانية، واستبدال القيمة يمحو ذلك بصمت.
UPDATE app_settings
   SET value = jsonb_set(value, '{ads}', '{
         "enabled": true,
         "test": true,
         "ios": {
           "banner": "ca-app-pub-3940256099942544/2934735716",
           "native": "ca-app-pub-3940256099942544/3986624511"
         },
         "android": {
           "banner": "ca-app-pub-3940256099942544/6300978111",
           "native": "ca-app-pub-3940256099942544/2247696110"
         }
       }'::jsonb, true),
       updated_at = now()
 WHERE key = 'premium';
