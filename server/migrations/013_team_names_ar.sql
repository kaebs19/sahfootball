-- 013_team_names_ar.sql — الأسماء العربية لأندية دوري روشن
--
-- لماذا هجرة لا إدخال يدوي من اللوحة؟ لأن هذا ما حدث فعلاً: الأسماء
-- أُدخلت مرة في قاعدة التطوير، ثم نُشرت النسخة الأولى على الإنتاج
-- فظهرت كل الفرق بأسمائها الإنجليزية — "Al-Ahli Jeddah" في تطبيق
-- عربي بالكامل. المعرفة كانت تعيش في قاعدة واحدة على جهاز واحد،
-- ولا تنجو من أي نشر جديد ولا من استعادة نسخة احتياطية.
--
-- المزوّد يرسل name_en فقط ولن يرسل العربية أبداً، فهذه بيانات
-- نملكها نحن لا هو — ومكان ما نملكه هو المستودع.
--
-- التحديث لا الإدراج: صفوف الفرق ينشئها المزامن من المزوّد (معرّفاته
-- هي مفاتيحنا الأساسية)، فالهجرة تكمل ما ينقصها فقط. وشرط
-- name_ar IS NULL يحمي أي تعديل يدوي لاحق من اللوحة: من صحّح اسماً
-- هناك لا تعيده الهجرة إلى قيمتها.
--
-- ولا تشترط وجود الصف: فريق لم يزامنه المزوّد بعد لا يُحدَّث، ويلتقط
-- اسمه حين تُعاد الهجرة أو يُعدَّل من اللوحة.
UPDATE teams AS t
   SET name_ar = v.name_ar
  FROM (VALUES
  (2928, 'الخليج'),
  (2929, 'الأهلي'),
  (2930, 'الفيصلي'),
  (2931, 'الفتح'),
  (2932, 'الهلال'),
  (2933, 'القادسية'),
  (2934, 'الاتفاق'),
  (2935, 'الرائد'),
  (2936, 'التعاون'),
  (2937, 'الوحدة'),
  (2938, 'الاتحاد'),
  (2939, 'النصر'),
  (2940, 'الشباب'),
  (2944, 'الفيحاء'),
  (2945, 'الحزم'),
  (2951, 'أبها'),
  (2956, 'ضمك'),
  (2961, 'العروبة'),
  (2977, 'الأخدود'),
  (10509, 'الخلود'),
  (10511, 'الرياض'),
  (10513, 'نيوم'),
  (26738, 'الدرعية')
) AS v(id, name_ar)
 WHERE t.id = v.id AND t.name_ar IS NULL;
