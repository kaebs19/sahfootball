-- 019 — أداة المضاعِف ×2، وجدول نقاط بمقياس أوضح.
--
-- المضاعِف: يختار اللاعب مباراة يثق بها فتتضاعف نقاطها. خمسة
-- مجاناً لكل لاعب في كل دوري وكل موسم.
--
-- لماذا عمود على التوقّع لا جدول "أرصدة"؟ لأن الرصيد مشتقّ لا
-- مخزّن: المستعمَل = عدد توقّعاته المضاعَفة في هذا الدوري وهذا
-- الموسم، والباقي = خمسة ناقص ذلك. جدول أرصدة منفصل يعني رقمين
-- يجب أن يتفقا — وأول عملية تُكتب في أحدهما وتفشل في الآخر تترك
-- لاعباً بمضاعفات وهمية أو مسروقة. هنا لا يمكن أن يختلفا: لا
-- وجود للرقم الثاني.
--
-- ويعطي هذا الاستردادَ مجاناً: من ألغى المضاعِف قبل الصافرة عاد
-- توقّعه إلى 1 فنقص المعدود من نفسه. ويعطي التجديد الموسمي مجاناً
-- أيضاً: الشرط على season، فالموسم الجديد يبدأ بخمسة بلا وظيفة
-- دورية تصفّر شيئاً.
ALTER TABLE predictions
  ADD COLUMN multiplier SMALLINT NOT NULL DEFAULT 1
  CONSTRAINT predictions_multiplier_allowed CHECK (multiplier IN (1, 2));

-- فهرس عدّ المستعمَل: يُسأل عند كل فتح لصفحة مباراة قابلة للتوقّع،
-- والشرط الجزئي يبقيه صغيراً — المضاعَفة قلة نادرة بحكم تعريفها.
CREATE INDEX idx_predictions_multiplied
  ON predictions (user_id, fixture_id)
  WHERE multiplier > 1;

-- مقياس النقاط الجديد: 100 / 75 / 50 بدل 5 / 3 / 2.
-- النسب هي هي، لكن الرقم الكبير يُقرأ كجائزة والصغير كعلامة
-- مدرسية — و"ضاعِف نقاطك" لا معنى له حين تكون النقطتان أربعاً.
UPDATE app_settings
   SET value = '{"exact":100,"diff":75,"outcome":50}'::jsonb,
       updated_at = now()
 WHERE key = 'scoring';

-- ونضرب النقاط المحتسَبة سلفاً في عشرين حتى لا ينكمش من لعب
-- بالمقياس القديم أمام من يلعب بالجديد على نفس اللوحة.
UPDATE predictions
   SET points = points * 20
 WHERE settled_at IS NOT NULL AND points IS NOT NULL;

-- إعدادات الأداة نفسها، لتُعدَّل من اللوحة لا من نشر جديد.
INSERT INTO app_settings (key, value)
VALUES ('multipliers', '{"factor":2,"free_per_season":5}'::jsonb)
ON CONFLICT (key) DO NOTHING;
