-- 007_leagues.sql — دعم أكثر من دوري
--
-- حتى الآن كان الدوري واحداً ومثبّتاً في متغيرات البيئة
-- (LEAGUE_ID=307). هذا الجدول ينقل القرار من ملف .env إلى القاعدة،
-- فيستطيع الأدمن إضافة دوري وتفعيله وإيقافه من اللوحة بلا نشر.
--
-- المفتاح الأساسي هو معرّف الدوري عند المزود — نفس القرار المشروح
-- في 001_init.sql للفرق والمباريات، ولنفس السبب تماماً: عمود
-- fixtures.league_id يحمل معرّف المزود أصلاً، فأي معرّف خاص بنا
-- كان سيفرض جدول ربط في كل مزامنة.

CREATE TABLE IF NOT EXISTS leagues (
  id             INTEGER PRIMARY KEY,       -- معرّف الدوري عند المزود
  name_en        TEXT NOT NULL,
  name_ar        TEXT,                      -- يُملأ يدوياً من اللوحة (المزود إنجليزي فقط)
  country        TEXT,
  logo_url       TEXT,
  -- الموسم لكل دوري على حدة وليس قيمة عامة: الباقة المجانية تخدم
  -- 2022–2024 فقط، وليس كل دوري عنده نفس الموسم المتاح.
  season         INTEGER NOT NULL,
  -- المفتاح الذي يتحكم بالتكلفة: كل دوري مفعّل يضاعف طلبات
  -- المزامنة، والحصة المجانية 100 طلب/يوم. الإيقاف يبقي بيانات
  -- الدوري ومبارياته كما هي ويخرجه من دورة المزامنة فقط.
  enabled        BOOLEAN NOT NULL DEFAULT true,
  sort_order     INTEGER NOT NULL DEFAULT 0, -- ترتيب العرض في التطبيق واللوحة
  last_synced_at TIMESTAMPTZ,                -- NULL = لم يُزامن بعد
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- مع تعدد الدوريات صار كل استعلام "مباريات هذا الدوري في هذا
-- الموسم" يصفّي على العمودين معاً — فهرس مركّب يخدمهما دفعة واحدة.
CREATE INDEX IF NOT EXISTS idx_fixtures_league_season ON fixtures (league_id, season);

-- بذرة الدوري المُعدّ حالياً في .env.
--
-- لماذا نبذر بدل ترك الجدول فارغاً؟ التركيب القائم فيه أكثر من 300
-- مباراة بـ league_id = 307. لو بدأ الجدول فارغاً لأصبحت تلك الصفوف
-- يتيمة: المزامنة تدور على الدوريات المفعّلة فلا تجد شيئاً، واللوحة
-- تعرض مباريات لدوري لا وجود له في قائمتها. البذرة تجعل الترقية
-- بلا أثر ملحوظ — كل شيء يعمل كما كان، بدوري واحد مفعّل.
--
-- ON CONFLICT DO NOTHING: إعادة تشغيل الهجرة (أو وجود الصف مسبقاً
-- بعد تعديل الأدمن لاسمه) لا تدهس ما في الجدول.
INSERT INTO leagues (id, name_en, name_ar, country, season)
VALUES (307, 'Saudi Pro League', 'دوري روشن السعودي', 'Saudi-Arabia', 2024)
ON CONFLICT (id) DO NOTHING;
