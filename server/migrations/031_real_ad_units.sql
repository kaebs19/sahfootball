-- 031 — وحدات الإعلانات الحقيقية من حساب AdMob.
--
-- تحلّ محل وحدات جوجل التجريبية التي زرعتها الهجرة 029. ومعرّف
-- التطبيق (وهو غير الوحدات) يبقى في Info.plist و AndroidManifest
-- لأن حزمة الإعلانات تقرؤه عند الإقلاع قبل أن يصل أي ردّ من خادمنا.
--
-- و`test` يبقى مفتاحاً حيّاً لا أثراً من الماضي: رفعُه يُعيد وحدات
-- جوجل التجريبية فوراً مهما كانت الوحدات المكتوبة هنا (راجع
-- premiumService.adUnits). وهذا ليس ترفاً — الضغط على إعلان حقيقي
-- في تطبيقك أثناء التجربة مخالفةٌ يُغلق بها حساب AdMob، وهي أسهل
-- غلطة تقع في التطوير. فقبل أي تجربة على جهاز:
--
--   UPDATE app_settings
--      SET value = jsonb_set(value, '{ads,test}', 'true'::jsonb)
--    WHERE key = 'premium';
--
-- jsonb_set لا استبدال الكائن كله: قد يكون الأدمن أطفأ الإعلانات
-- أو عدّل شيئاً آخر في المفتاح، واستبدال القيمة يمحو ذلك بصمت.
UPDATE app_settings
   SET value = jsonb_set(value, '{ads}', '{
         "enabled": true,
         "test": false,
         "ios": {
           "banner": "ca-app-pub-8219247197168750/9677590138",
           "native": "ca-app-pub-8219247197168750/7337482772"
         },
         "android": {
           "banner": "ca-app-pub-8219247197168750/3398237769",
           "native": "ca-app-pub-8219247197168750/3292145185"
         }
       }'::jsonb, true),
       updated_at = now()
 WHERE key = 'premium';
