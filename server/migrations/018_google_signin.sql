-- 018_google_signin.sql — الدخول بحساب جوجل
--
-- عمود مستقل عن apple_sub لا عمود "provider + id" مشترك: المستخدم
-- الواحد قد يربط الاثنين معاً (دخل بآبل من الهاتف وبجوجل من
-- المتصفح)، وعمودان يسمحان بذلك بينما العمود المشترك يفرض اختياراً
-- لا سبب له.
--
-- والتكلفة عمود فارغ لأغلب الصفوف، وهو أرخص من جدول هويات مستقل
-- يفرض JOIN على كل تسجيل دخول.
ALTER TABLE users ADD COLUMN IF NOT EXISTS google_sub TEXT;

-- UNIQUE لا مجرد فهرس: معرّف جوجل الواحد لا يجوز أن يشير إلى
-- حسابين — وإلا صار الدخول به عشوائياً بين الاثنين.
-- والفهرس جزئي: يفهرس من ربط جوجل فقط، لا كل المستخدمين، ويسمح
-- بعدد غير محدود من NULL (بخلاف UNIQUE العادي في بعض القواعد).
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_google_sub
  ON users (google_sub) WHERE google_sub IS NOT NULL;
