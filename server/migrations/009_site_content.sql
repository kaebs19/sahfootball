-- لصار كل تعديل حرف يمر بمطوّر ونشر نسخة. الجدول ينقلها إلى
-- القاعدة فتصير قابلة للتحرير من اللوحة — نفس منطق app_settings.
--
-- ⚠️ تنبيه قانوني مهم — اقرأه قبل النشر:
-- النصوص المبذورة أدناه (الخصوصية والشروط خصوصاً) كتبها مطوّر
-- وليس محامياً، ولم تُراجع قانونياً إطلاقاً. هي *مسودة بداية*
-- صالحة للعمل عليها، لا وثيقة نهائية. على مشغّل التطبيق مراجعتها
-- مع مختص وتعديل أسماء الجهة وبريد التواصل والدولة والقانون
-- الواجب التطبيق قبل نشرها.
-- وتحديداً: مراجعة App Store تشترط رابط سياسة خصوصية يعمل فعلاً
-- ويصف ما يجمعه التطبيق بدقة — رابط مكسور أو نص عام لا يطابق
-- سلوك التطبيق سبب رفض متكرر في المراجعة.

CREATE TABLE IF NOT EXISTS site_pages (
  -- المفتاح هو الـ slug نفسه وليس معرّفاً رقمياً: الصفحات مجموعة
  -- ثابتة معروفة مسبقاً (خصوصية، شروط، عن، تواصل)، والموقع يطلبها
  -- باسمها لا برقمها (/privacy لا /pages/3). المعرّف الرقمي كان
  -- سيفرض جدول ربط ذهنياً بين الرابط والصف بلا فائدة.
  slug       TEXT PRIMARY KEY,
  title      TEXT NOT NULL,
  -- Markdown خام وليس HTML — وهذا قرار أمني لا تفضيل شكلي.
  -- لو خزّنّا HTML لكان أي محتوى يكتبه الأدمن يصل المتصفح كما هو،
  -- فيتحول حساب أدمن مخترق إلى XSS مخزّن على كل زائر. النص هنا
  -- يمر دائماً بـ utils/safeMarkdown الذي يهرب HTML أولاً ثم
  -- يطبّق تحويلاً محدوداً فوق النص المهرَّب.
  body       TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- صندوق رسائل نموذج "تواصل معنا".
--
-- لماذا في القاعدة وليس بريداً يُرسل فوراً؟
-- MAIL_DRIVER لا يزال 'console' (انظر services/mailer.js): البريد
-- يُطبع في اللوق ولا يغادر السيرفر. نموذج تواصل يعتمد على الإرسال
-- اليوم يعني ابتلاع كل رسالة تصل بصمت — المستخدم يرى "تم الإرسال"
-- ولا أحد يقرأ رسالته أبداً. التخزين يجعل الرسالة موجودة بيقين،
-- وإضافة إشعار بريدي لاحقاً تصير تحسيناً فوق مصدر حقيقة قائم لا
-- بديلاً عنه.
CREATE TABLE IF NOT EXISTS contact_messages (
  id         BIGSERIAL PRIMARY KEY,
  -- الاسم والموضوع اختياريان (قد يرسل زائر مستعجل رسالة بلا عنوان)،
  -- والرسالة وحدها إلزامية — رسالة فارغة لا معنى لحفظها.
  name       TEXT,
  email      TEXT,
  subject    TEXT,
  message    TEXT NOT NULL,
  -- read_at وليس is_read BOOLEAN: نفس منطق suspended_at في 008 —
  -- التاريخ يحمل الحالة (NULL = غير مقروءة) ويضيف "متى قُرئت" مجاناً.
  read_at    TIMESTAMPTZ,
  -- عنوان الطلب: النموذج عام بلا مصادقة، فهو هدف إغراق طبيعي.
  -- حفظ العنوان يسمح للأدمن أن يرى أن عشرين رسالة جاءت من مصدر
  -- واحد بدل أن يظنها عشرين شخصاً.
  ip         TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- صندوق الوارد يفتح دائماً على "الأحدث أولاً".
CREATE INDEX IF NOT EXISTS idx_contact_messages_created
  ON contact_messages (created_at DESC);

-- فهرس جزئي للفلتر الوحيد الآخر في اللوحة (غير المقروءة) وللعدّاد
-- الذي يرسم الشارة في الشريط الجانبي. حجمه = عدد الرسائل غير
-- المقروءة (حفنة) لا عدد الرسائل كلها — نفس فكرة idx_users_suspended.
CREATE INDEX IF NOT EXISTS idx_contact_messages_unread
  ON contact_messages (created_at DESC) WHERE read_at IS NULL;

