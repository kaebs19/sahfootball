## ما الذي نجمعه

### بيانات تعطينا إياها بنفسك

- **البريد الإلكتروني** — لإنشاء الحساب، وتسجيل الدخول، واستعادة كلمة المرور.
- **الاسم الظاهر** — يظهر لبقية المستخدمين في لوحات الصدارة وفي القروبات التي تشترك فيها.
- **صورة الحساب (اختيارية)** — تظهر بجانب اسمك. لا يُشترط رفعها لاستخدام التطبيق، ويمكنك حذفها في أي وقت.
- **كلمة المرور** — لا نحفظها كنص مقروء إطلاقاً، بل نحفظ بصمة مشفّرة لها لا يمكن عكسها إلى الكلمة الأصلية.

### بيانات تنشأ عن استخدامك للتطبيق

- **توقّعاتك** لنتائج المباريات، ووقت تسجيل كل توقّع.
- **نقاطك وترتيبك**، وهي محسوبة من توقّعاتك ومن النتائج الفعلية للمباريات.
- **قروباتك** — القروبات التي أنشأتها أو انضممت إليها برمز دعوة، وعضويتك فيها.
- **رسائل التواصل** التي ترسلها عبر نموذج «تواصل معنا»، ومعها عنوان الشبكة (IP) الذي أُرسلت منه لمنع الإغراق الآلي.

### تسجيل الدخول باستخدام Apple

عند اختيارك «تسجيل الدخول باستخدام Apple» نستلم من Apple معرّفاً ثابتاً لحسابك، وبريداً إلكترونياً قد يكون بريداً وسيطاً من Apple إن اخترت إخفاء بريدك الحقيقي. لا نستلم كلمة مرور حسابك لدى Apple ولا نستطيع الوصول إليه.

### الاشتراكات المدفوعة

نخطّط لتقديم اشتراكات مدفوعة داخل التطبيق. تتم عملية الدفع بالكامل عبر متجر Apple: **لا نستلم ولا نخزّن أرقام بطاقاتك ولا بيانات الدفع**، وإنما حالة اشتراكك فقط (نشط أو منتهٍ) لنعرف ما الذي نفتحه لك.

