- قيم النقاط (النتيجة الدقيقة، فارق الأهداف، صحة الاتجاه) قابلة للتعديل من الإدارة لموازنة اللعبة. أي تعديل يسري على ما يُحتسب بعده.
- نبذل جهدنا في دقة البيانات وتوقيتها، ولا نضمن خلوّها من الخطأ أو الانقطاع.

## القروبات

