## طبيعة الخدمة

ملك التوقعات لعبة توقّعات ترفيهية بين الأصدقاء: تتوقّع نتائج المباريات، فتُحتسب لك نقاط بحسب دقة توقّعك، وتتنافس في لوحة صدارة عامة أو داخل قروب خاص.

**الخدمة ليست مقامرة ولا رهاناً**: لا تُدفع أموال مقابل التوقّعات، ولا تُوزَّع أرباح مالية على النتائج. النقاط قيمة داخل التطبيق فقط، لا قيمة نقدية لها ولا يمكن تحويلها أو بيعها.

## الحساب

- تلتزم بتقديم بريد إلكتروني صحيح تملكه، وبالمحافظة على سرّية كلمة مرورك.
- أنت مسؤول عن كل نشاط يجري عبر حسابك.
- حساب واحد لكل شخص. إنشاء حسابات متعددة للتلاعب بالترتيب أو بمسابقات القروبات سبب كافٍ للإيقاف.
- أبلغنا فوراً عند اشتباهك بوصول أحد إلى حسابك.

## قواعد الاستخدام

يُمنع أثناء استخدام الخدمة:

- استخدام اسم ظاهر أو صورة مسيئة أو مخالفة للآداب أو منتحِلة لشخصية غيرك.
- الإساءة إلى المستخدمين أو التحرش بهم أو بثّ خطاب كراهية.
- محاولة اختراق الخدمة أو تعطيلها أو الوصول إلى بيانات غيرك.
- استخدام برامج آلية لإرسال التوقّعات أو للتلاعب بالنقاط.
- استخدام الخدمة لأي غرض غير قانوني.

للإدارة أن تحذف اسماً أو صورة مخالفة، أو توقف الحساب، أو تحذفه في الحالات الجسيمة أو المتكررة.

