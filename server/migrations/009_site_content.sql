# عن ملك التوقعات

**توقّع بذكاء. اجمع التاج. اجلس على العرش.**

ملك التوقعات لعبة توقّعات كرة قدم بالعربية، فكرتها بسيطة: قبل كل مباراة تكتب النتيجة التي تتوقعها، وبعد صافرة النهاية تُحتسب لك نقاط بحسب دقة توقّعك — ثم تكتشف من فيكم يفهم في الكرة فعلاً.

## كيف تعمل

1. **اختر المباراة** من جدول اليوم أو من المباريات القادمة.
2. **اكتب توقّعك** قبل بداية المباراة. بعد انطلاقها يُقفل التوقّع.
3. **اجمع نقاطك** بعد انتهاء المباراة: النتيجة الدقيقة تعطي أعلى نقاط، ثم فارق الأهداف الصحيح، ثم صحة الاتجاه (فوز أو تعادل أو خسارة).
4. **تنافس** في لوحة الصدارة العامة، أو أنشئ قروباً خاصاً وادعُ أصدقاءك برمز الدعوة.

## ما الذي يميزه

- **عربي أصيل** — أسماء الأندية والدوريات بالعربية، وواجهة مصممة للقراءة من اليمين لليسار.
- **قروبات خاصة** — دوري بينك وبين أصدقائك أو زملاء العمل، بترتيبه المستقل.
- **نتائج محدَّثة** — جدول المباريات ونتائجها تصل تلقائياً من مزوّد بيانات متخصص.
- **بلا مقامرة** — لا رهان ولا أموال، منافسة على النقاط والمركز فقط.

## الدوريات المتاحة

نبدأ بدوري روشن السعودي، ونضيف دوريات أخرى تباعاً بحسب ما يطلبه اللاعبون.

