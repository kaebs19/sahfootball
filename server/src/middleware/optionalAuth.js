// optionalAuth — هوية إن وُجدت، ومرور بلا هوية إن لم توجد.
//
// لمسارات القراءة العامة التي تُشخصَن فقط: قائمة الدوريات مثلاً
// بياناتها عامة (هي على الموقع للجميع)، لكن مع توكن صالح تحمل
// علامة "أتابعه؟" لصاحبه. requireAuth كان يقفلها كلها، فيراها
// الضيف 401 ولا يستطيع حتى اختيار دوري يتصفّح مبارياته.
//
// لا فحص إيقاف هنا عمداً: هذا الحارس لا يفتح فعلاً ولا يكشف
// بيانات غير بيانات صاحب التوكن نفسه، والموقوف يُصدّ عند أول مسار
// محمي فعلاً. أي توكن فاسد أو منتهٍ يُعامَل كغياب لا كخطأ — المسار
// عام أصلاً، ورفضه لأن توكناً قديماً علق في العميل يخالف غرضه.
const jwt = require('jsonwebtoken');

function optionalAuth(req, res, next) {
  const [scheme, token] = (req.headers.authorization || '').split(' ');
  if (scheme === 'Bearer' && token) {
    try {
      req.userId = jwt.verify(token, process.env.JWT_SECRET).sub;
    } catch (_) {
      // توكن غير صالح = ضيف
    }
  }
  next();
}

module.exports = optionalAuth;
